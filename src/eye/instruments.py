def normalize_instrument(raw: str) -> str:
    s = (raw or "").strip().lower().replace("ё", "е")

    if "скрип" in s:
        if "1" in s:
            return "первые скрипки"
        if "2" in s:
            return "вторые скрипки"
        return "первые скрипки"

    # ======= Ветка Саксов =======
    if "сакс" in s:
        if "сопран" in s:
            return "сопрано-саксофон"
        if "альт-сакс" in s:
            return "альт-саксофон"
        if "тенор" in s:
            return "тенор-саксофон"
        if "барит" in s:
            return "баритон-саксофон"
        if "бас" in s:
            return "бас-саксофон"
        return "саксофон"

    if "альт" in s:
        return "альт"
    if "виолонч" in s:
        return "виолончель"
    if "контрабас" in s:
        return "контрабас"

    if "флейт" in s:
        return "флейта"
    if "гобо" in s:
        return "гобой"
    if "кларнет" in s:
        return "кларнет"
    if "фагот" in s:
        return "фагот"

    if "валторн" in s:
        return "валторна"
    if "труба" in s:
        return "труба"
    if "тромбон" in s:
        return "тромбон"
    if "туба" in s:
        return "туба"

    if "удар" in s or "перкус" in s:
        return "ударные"
    if "фортеп" in s or "пианино" in s:
        return "фортепиано"
    if "арфа" in s:
        return "арфа"
    if "дириж" in s:
        return "дирижёр"

    return s or "неизвестно"
